"""Embed the shared English catalog; applications need no external language files."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BEGIN = '    // BEGIN GENERATED LOCALIZATION'
END = '    // END GENERATED LOCALIZATION'


def literal(value):
    return json.dumps(value, ensure_ascii=False)


def outputs():
    catalog = json.loads((ROOT / 'locales/en.json').read_text(encoding='utf-8'))
    if not catalog or any(not isinstance(k, str) or not isinstance(v, str) or not v for k, v in catalog.items()):
        raise ValueError('Catalog must contain nonempty text translations')
    pairs = sorted(catalog.items())
    cs = BEGIN + '''
    public static class UiText {
        static string preference="system";
        public static string Normalize(string value) {
            value=(value??"").Replace('_','-');
            if(value.StartsWith("zh",StringComparison.OrdinalIgnoreCase))return "zh-CN";
            if(value.StartsWith("en",StringComparison.OrdinalIgnoreCase))return "en";
            return "system";
        }
        public static string Resolve(string value,string systemCulture) {
            string selected=Normalize(value);
            if(selected!="system")return selected;
            return (systemCulture??"").StartsWith("zh",StringComparison.OrdinalIgnoreCase)?"zh-CN":"en";
        }
        public static void UseLanguage(string value){preference=Normalize(value);}
        public static string Get(string source) {
            if(source==null)return "";
            string translated;
            return Resolve(preference,System.Globalization.CultureInfo.CurrentUICulture.Name)=="en"&&English.TryGetValue(source,out translated)?translated:source;
        }
        static readonly Dictionary<string,string> English=new Dictionary<string,string> {
'''
    cs += ',\n'.join('            {' + literal(k) + ',' + literal(v) + '}' for k, v in pairs)
    cs += '\n        };\n    }\n' + END
    cpp = '''// Generated by tools/i18n/generate.py. Do not edit the catalog here.
#pragma once
#include <QString>
#include <QLocale>
#include <QMap>
namespace wpsclock {
class UiText {
    static QString &preference(){static QString value="system";return value;}
public:
    static QString normalize(QString value){
        value.replace('_','-');
        if(value.startsWith("zh",Qt::CaseInsensitive))return "zh-CN";
        if(value.startsWith("en",Qt::CaseInsensitive))return "en";
        return "system";
    }
    static QString resolve(const QString &value,const QString &systemCulture){
        QString selected=normalize(value);
        return selected!="system"?selected:(systemCulture.startsWith("zh",Qt::CaseInsensitive)?QString("zh-CN"):QString("en"));
    }
    static void useLanguage(const QString &value){preference()=normalize(value);}
    static QString get(const QString &source){
        if(resolve(preference(),QLocale::system().name())!="en")return source;
        static const QMap<QString,QString> english={
'''
    cpp += ',\n'.join('            {QString::fromUtf8(' + literal(k) + '),QString::fromUtf8(' + literal(v) + ')}' for k, v in pairs)
    cpp += '''
        };
        return english.value(source,source);
    }
};
inline QString ui(const QString &source){return UiText::get(source);}
inline QString ui(const char *source){return ui(QString::fromUtf8(source));}
}
'''
    windows = ROOT / 'apps/windows/WpsClock.cs'
    source = windows.read_text(encoding='utf-8-sig')
    start = source.index(BEGIN)
    finish = source.index(END, start) + len(END)
    return {windows: b'\xef\xbb\xbf' + (source[:start] + cs + source[finish:]).encode('utf-8'),
            ROOT / 'apps/linux/i18n.h': cpp.encode('utf-8')}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if embedded catalogs are stale')
    args = parser.parse_args()
    stale = []
    for path, data in outputs().items():
        if args.check:
            if not path.exists() or path.read_bytes() != data:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_bytes(data)
    if stale:
        raise SystemExit('Regenerate embedded translations: ' + ', '.join(stale))
    print('PASS: embedded translations are current' if args.check else 'Updated embedded translations')


if __name__ == '__main__':
    main()
